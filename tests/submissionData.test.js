import assert from 'node:assert/strict';
import { fileRules,validateFiles,MB,escapeHtml,publishedWork } from '../src/submissionData.js';
import { publishedDetail } from '../src/publishedViews.js';
import { validatePublicSupabaseConfig } from '../src/backendConfig.js';
assert.equal(validatePublicSupabaseConfig('',''),false);
assert.equal(validatePublicSupabaseConfig('https://example.supabase.co','sb_publishable_test'),true);
assert.throws(() => validatePublicSupabaseConfig('https://example.supabase.co','sb_secret_test'));
const secretJwt = `header.${btoa(JSON.stringify({role:'service_role'}))}.signature`;
assert.throws(() => validatePublicSupabaseConfig('https://example.supabase.co',secretJwt));
assert.ok(!('video' in fileRules));
const elements = Object.fromEntries(Object.keys(fileRules).map(name => [name,{files:[]} ]));
const form = {elements};
assert.ok(validateFiles(form).errors.length);
elements.cover.files = [{size:1000,type:'image/png'}];
assert.deepEqual(validateFiles(form).errors,[]);
elements.gallery.files = Array.from({length:13},() => ({size:1000,type:'image/png'}));
assert.ok(validateFiles(form).errors.length);
elements.gallery.files = [{size:9*MB,type:'image/png'}];
assert.ok(validateFiles(form).errors.length);
elements.gallery.files = [{size:1000,type:'image/svg+xml'}];
assert.ok(validateFiles(form).errors.length);
assert.equal(escapeHtml('<script>"x"</script>'),'&lt;script&gt;&quot;x&quot;&lt;/script&gt;');
const work = publishedWork({id:'id',creator_id:'creator',student_name:'<img onerror=alert(1)>',grade:'2025级',title:'<script>alert(1)</script>',category:'3D',year:'2026',summary:'简介',roles:'独立完成',files:[{kind:'cover',url:'https://example.com/cover'}]},[]);
assert.equal(work.kind,'model');
assert.equal(work.uploaded,true);
assert.deepEqual(work.authors,[]);
const markup = publishedDetail(work,'全部作品');
assert.ok(!markup.includes('<script>'));
assert.ok(!markup.includes('<img onerror'));
assert.ok(markup.includes('&lt;script&gt;'));
